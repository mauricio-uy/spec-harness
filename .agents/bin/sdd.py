def latest_version(unit: str) -> tuple[int, int, int]:
    prefix = re.escape(f"{unit}/v" if unit else "v")
    versions = [
        tuple(int(x) for x in m.groups()) for tag in git("tag", "--list", check=False).splitlines()
        if (m := re.fullmatch(prefix + r"(\d+)\.(\d+)\.(\d+)", tag.strip()))
    ]
    return max(versions, default=(0, 0, 0))


def bump(version: tuple[int, int, int], level: str) -> tuple[int, int, int]:
    major, minor, patch = version
    if level == "major" and major > 0:
        return major + 1, 0, 0
    if level in ("major", "minor"):
        return major, minor + 1, 0
    return major, minor, patch + 1


def is_breaking(sl: Slice) -> bool:
    breaking = sl.front.get("breaking", False)
    return breaking is True or (isinstance(breaking, list) and bool(breaking))


def commit_title(sl: Slice) -> str:
    title = sl.front.get("title", sl.id)
    subject = title if title[:2].isupper() else title[:1].lower() + title[1:]
    bang = "!" if is_breaking(sl) else ""
    return f"{CHANGES[sl.front['change']][0]}({sl.front.get('capability')}){bang}: {subject}"


def close_notes(sl: Slice) -> list[str]:
    close = sl.dir / "close.md"
    found = sections(close.read_text(encoding="utf-8")) if close.exists() else {}
    notes = []
    for section, label in (("Deviations", "Deviation"), ("Debt", "Debt")):
        for line in content(found.get(section, "")):
            text = line.removeprefix("- ").strip()
            if text.lower() not in ("none", "n/a"):
                notes.append(f"- {label}: {text}")
    return notes


def pr_body(sl: Slice) -> str:
    lines = [sl.goal(), "", "## Acceptance criteria", ""]
    lines += [f"- {sl.id}/AC-{n}: {text}" for n, text in sl.acs]
    notes = close_notes(sl)
    if notes:
        lines += ["", "## Notes", "", *notes]
    # Trailers must be the last paragraph of the squash commit.
    lines += ["", *([f"BREAKING CHANGE: {sl.goal()}"] if is_breaking(sl) else []), f"Slice: {sl.id}"]
    return "\n".join(lines) + "\n"


def cmd_pr(args, config) -> int:
    sl = Slice(args.slice)
    if sl.status != "done":
        fail(f"{sl.id} is {sl.status}; close it with sdd-close before opening its pull request")
    if sl.front.get("change") not in CHANGES:
        fail(f"{sl.id} has an invalid change type")
    if args.title:
        print(commit_title(sl))
    elif args.body:
        print(pr_body(sl), end="")
    else:
        print(f"{commit_title(sl)}\n\n{pr_body(sl)}", end="")
    return 0


def release_tags() -> list[tuple[str, str, str]]:
    """(name, commit, message) of every annotated release tag (`v1.2.0`, `api/v1.2.0`)."""
    out = git("for-each-ref", "refs/tags", "--format=%(refname:short)%00%(objecttype)%00%(*objectname)%00%(contents)%01", check=False)
    tags = []
    for record in out.split("\x01"):
        fields = record.lstrip("\n").split("\0")
        if len(fields) == 4 and fields[1] == "tag" and RELEASE_TAG_RE.fullmatch(fields[0]):
            tags.append((fields[0], fields[2], fields[3]))
    return tags


def tag_unit(tag: str) -> str:
    """Release unit of a tag: `api` for `api/v1.2.0`, the root unit (`""`) for `v1.2.0`."""
    return tag.rpartition("/v")[0] if "/" in tag else ""


def tagged_slices(message: str) -> set[str]:
    """Slices named in a release tag subject: `Release v1.2.0 (S-011, S-012)`."""
    m = re.search(r"\(((?:S-\d+(?:, )?)+)\)\s*$", message.split("\n", 1)[0])
    return set(m.group(1).split(", ")) if m else set()


def first_parent_history() -> list[tuple[str, list[str], list[str]]]:
    """(commit, slice IDs, changed files) of every first-parent commit, newest first, in one git call."""
    # --no-renames: a slice moved from changes/ to archive/ must show as added, for the fallback below.
    out = git("-c", "core.quotePath=false", "log", "--first-parent", "-m", "--name-status", "--no-renames",
              "--format=%x01%H%x00%B%x02", check=False)
    history = []
    for record in out.split("\x01")[1:]:
        head, _, changes = record.partition("\x02")
        sha, _, message = head.partition("\0")
        files, added = [], []
        for line in changes.splitlines():
            status, *paths = line.split("\t")
            files += paths
            if status.startswith("A"):
                added += paths
        ids = SLICE_TRAILER_RE.findall(message)
        if not ids:
            # Fallback when the trailer was edited out: the closing commit adds the archived slice.
            ids = sorted({m.group(1) for path in added if (m := re.match(r"\.agents/docs/archive/(S-\d+)-", path))})
        history.append((sha, ids, files))
    return history


def inside(path: str, unit_path: str) -> bool:
    unit_path = unit_path.strip("/")
    return unit_path in ("", ".") or path == unit_path or path.startswith(unit_path + "/")


def unit_breaking(sl: Slice, unit: str) -> bool:
    breaking = sl.front.get("breaking", False)
    return breaking is True or (isinstance(breaking, list) and unit in breaking)


def release_plan(units: list[dict]) -> tuple[list[dict], list[str]]:
    """Per release unit: the slices merged since its own last tag whose commit touched its files.

    A squash merge makes each slice one commit, so its own diff (sha^..sha) is exactly what it changed.
    Each unit is tagged on its last slice's commit, bumped by the strongest change among its slices.
    Also returns the slices merged since the newest release tag whose commit touched no unit at all:
    they are never released, and reporting only recent ones keeps the notice from repeating.
    """
    names = {u.get("name", "") for u in units}
    history = first_parent_history()
    tags = release_tags()
    slices: dict[str, Slice] = {}

    def closed(sid: str) -> Slice:
        if sid not in slices:
            sl = slices[sid] = Slice(sid)
            if sl.status != "done" or sl.front.get("change") not in CHANGES:
                fail(f"{sid} is merged but not closed (status {sl.status}, change {sl.front.get('change')})")
            breaking = sl.front.get("breaking")
            unknown = set(breaking) - names if isinstance(breaking, list) else set()
            if unknown:
                fail(f"{sid} lists unknown release units as breaking: {', '.join(sorted(unknown))}")
        return slices[sid]

    def touches(files: list[str], unit: dict) -> bool:
        return not unit.get("name") or any(inside(f, p) for f in files for p in unit.get("paths", ["."]))

    def since(tagged: set[str]) -> list[tuple[str, list[str], list[str]]]:
        """The commits after the newest of `tagged`, oldest first."""
        pending = []
        for commit in history:
            if commit[0] in tagged:
                break
            pending.append(commit)
        return pending[::-1]

    untouched = sorted({
        sid for _, ids, files in since({commit for _, commit, _ in tags})
        if not any(touches(files, u) for u in units) for sid in ids
    })

    plan = []
    for unit in units:
        name = unit.get("name", "")
        own = [(commit, message) for tag, commit, message in tags if tag_unit(tag) == name]
        released = set().union(*(tagged_slices(message) for _, message in own))
        chosen, target = [], None
        for sha, ids, files in since({commit for commit, _ in own}):
            if not touches(files, unit):
                continue
            for sid in ids:
                if sid not in released:
                    chosen.append(closed(sid))
                    target = sha
        if not chosen:
            continue
        levels = ["major" if unit_breaking(sl, name) else CHANGES[sl.front["change"]][2] for sl in chosen]
        level = max(levels, key=["patch", "minor", "major"].index)
        version = ".".join(map(str, bump(latest_version(name), level)))
        plan.append({
            "name": name,
            "slices": chosen,
            "version": version,
            "tag": f"{name}/v{version}" if name else f"v{version}",
            "target": target,
        })
    return plan, untouched


def release_notes(slices: list[Slice], unit: str) -> str:
    """Keep a Changelog sections for one release, carried in the tag message and the GitHub Release."""
    entries: dict[str, list[str]] = {}
    for sl in slices:
        prefix = "**BREAKING:** " if unit_breaking(sl, unit) else ""
        entries.setdefault(CHANGES[sl.front["change"]][1], []).append(f"- {prefix}{sl.goal()} ({sl.id})")
    categories = [category for _, category, _ in CHANGES.values() if category in entries]
    return "\n".join(f"### {category}\n\n" + "\n".join(entries[category]) + "\n" for category in categories)


def cmd_release(args, config) -> int:
    plan, untouched = release_plan(config.get("units") or [{"name": "", "paths": ["."]}])
    for sid in untouched:
        print(f"{sid} touches no release unit: not released")
    if not plan:
        print("nothing to release")
        return 0

    for p in plan:
        target = git("rev-parse", "--short", p["target"]).strip()
        print(f"{p['tag']:<20} {target}  {', '.join(sl.id for sl in p['slices'])}")
    if not args.apply:
        print("\ndry run: pass --apply to create these annotated tags")
        return 0

    for p in plan:
        message = f"Release {p['tag']} ({', '.join(sl.id for sl in p['slices'])})\n\n{release_notes(p['slices'], p['name'])}"
        # Verbatim, or git strips the notes' `###` headings as comments.
        subprocess.run(["git", "tag", "-a", p["tag"], p["target"], "--cleanup=verbatim", "-F", "-"], cwd=ROOT, input=message, text=True, check=True)
    print(f"released {', '.join(p['tag'] for p in plan)}")
    return 0


def cmd_changelog(args, config) -> int:
    units = [u.get("name", "") for u in config.get("units") or []]
    if units and args.unit is None:
        fail(f"this project has release units; pass --unit with one of: {', '.join(units)}")
    if args.unit is not None and args.unit not in units:
        fail(f"unknown release unit: {args.unit}")
    prefix = f"{args.unit}/v" if args.unit else "v"
    releases = []
    for name, _, message in release_tags():
        if m := re.fullmatch(re.escape(prefix) + r"(\d+)\.(\d+)\.(\d+)", name):
            date_ = git("for-each-ref", f"refs/tags/{name}", "--format=%(taggerdate:short)").strip()
            releases.append((tuple(map(int, m.groups())), date_, message.split("\n", 1)[1].strip() if "\n" in message else ""))
    text = CHANGELOG_HEADER + "".join(
        f"\n## [{'.'.join(map(str, version))}] - {date_}\n\n{notes}\n" for version, date_, notes in sorted(releases, reverse=True)
    )
    if args.output:
        Path(args.output).write_text(text, encoding="utf-8")
        print(f"wrote {args.output}")
    else:
        print(text, end="")
    return 0


