#!/usr/bin/env python3
"""spec-harness CLI: lifecycle gates, status and releases for spec-driven slices.

Documents live in .agents/docs/ (ideas, changes, archive, specs, adr, runbooks)
and are mapped by the generated .agents/docs/index.md.

Commands (run from anywhere inside the repository):
  init                      add the managed block to AGENTS.md and generate the index
  index [--check]           regenerate the index, or verify it and AGENTS.md are current
  status [SLICE]            list open slices, or show one slice and its next gate
  check SLICE               verify the gate to the next status (runs tests when needed)
  advance SLICE             check the gate and move the slice to the next status
  reopen SLICE [--base REF] send a slice back to draft and unfreeze its acceptance tests; a closed
                            slice can be reopened until it reaches the base branch (default origin/main)
  accept ADR                accept a proposed ADR and supersede the one it replaces
  lint                      check links, ID references, AC-to-test traceability and vocabulary
  verify [--base REF] [--title TEXT] [--body TEXT]
                            for CI on pull requests: lint, open slices and the slices the pull
                            request closes still meet their gates (frozen tests intact), and the
                            pull request closes its slice properly
  next-id {idea,slice,adr}  print the next free ID
  pr SLICE [--title|--body] print the pull request title and body of a closed slice
  release [--apply]         after merging, tag every release unit touched by the slices merged
                            since the last release; the tag message carries the release notes
  changelog [--unit NAME] [--output FILE]
                            render CHANGELOG.md from the release tags

Optional configuration in .agents/config.toml:
  [tests]
  paths = ["tests"]         # where to look for acceptance test tags (default: whole repo)
  slice = "pytest {files}"  # runs the slice's acceptance tests: {files} and {dirs} expand to their
                            # files and folders, {id} to S-012 and {ident} to S012 (for test names)
  full = "pytest"           # runs the full suite
  support = ["tests/acceptance/helpers"]  # acceptance helpers frozen with the tests (globs or folders)
  red_exit = [1]            # exit codes that count as failing on missing behavior (default: any but 0)

  [[units]]                 # release units (default: one unit at the repository root)
  name = "api"
  paths = ["services/api"]

Commands may be strings or argument lists. Requires Python 3.11+ and git.
"""
