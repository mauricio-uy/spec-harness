def git(*args: str, check: bool = True) -> str:
    result = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True)
    if check and result.returncode:
        fail(result.stderr.strip() or f"git {' '.join(args)} failed")
    return result.stdout if result.returncode == 0 else ""


# --- spec documents ---------------------------------------------------------

def parse_value(value: str):
    if value in ("true", "false"):
        return value == "true"
    if value.startswith("[") and value.endswith("]"):
        return [item.strip() for item in value[1:-1].split(",") if item.strip()]
    return value


def strip_yaml_comment(line: str) -> str:
    return re.sub(r"(^|\s)#.*", "", line).rstrip()


def parse_front(text: str) -> tuple[dict, str]:
    match = FRONT_RE.match(text)
    if not match:
        return {}, text
    data = {}
    for line in match.group(1).splitlines():
        key, sep, value = strip_yaml_comment(line).partition(":")
        if sep and not line.startswith((" ", "\t")):
            data[key.strip()] = parse_value(value.strip())
    return data, text[match.end():]


def set_front(path: Path, key: str, value) -> None:
    text = path.read_text(encoding="utf-8")
    match = FRONT_RE.match(text) or fail(f"{path} has no front matter")
    block = match.group(1)
    line = f"{key}: {str(value).lower() if isinstance(value, bool) else value}"
    pattern = re.compile(rf"^{re.escape(key)}:[^\n]*$", re.M)

    def replace(match: re.Match) -> str:
        # Keep a trailing comment, aligned to its original column when possible.
        comment = re.search(r"(^|\s)(#.*)$", match.group(0))
        if not comment:
            return line
        column = comment.start(2)
        return (line.ljust(column) if len(line) < column else line + " ") + comment.group(2)

    if pattern.search(block):
        block = pattern.sub(replace, block, count=1)
    else:
        block += f"\n{line}"
    path.write_text(f"---\n{block}\n---\n{text[match.end():]}", encoding="utf-8")


def sections(body: str) -> dict[str, str]:
    found: dict[str, list[str]] = {}
    current = None
    for line in COMMENT_RE.sub("", body).splitlines():
        heading = re.match(r"#{1,6}\s+(.+?)\s*$", line)
        if heading:
            current = heading.group(1)
            found[current] = []
        elif current:
            found[current].append(line)
    return {name: "\n".join(lines) for name, lines in found.items()}


def content(text: str) -> list[str]:
    return [line.strip() for line in text.splitlines() if line.strip() not in ("", "-")]


def placeholders(text: str) -> list[str]:
    match = FRONT_RE.match(text)
    front = "\n".join(strip_yaml_comment(l) for l in match.group(1).splitlines()) if match else ""
    visible = front + COMMENT_RE.sub("", text[match.end():] if match else text)
    return [p for p in PLACEHOLDERS if p in visible]


def active_acs(body: str) -> list[tuple[int, str]]:
    criteria = sections(body).get("Acceptance criteria", "")
    return [(int(n), text) for strike, n, text in AC_RE.findall(criteria) if not strike]


class Slice:
    def __init__(self, slice_id: str):
        self.id = slice_id.upper()
        candidates = [
            d for parent in ("changes", "archive") if (DOCS / parent).is_dir()
            for d in (DOCS / parent).iterdir()
            if d.is_dir() and (d.name == self.id or d.name.startswith(self.id + "-"))
        ]
        if not candidates:
            fail(f"slice {self.id} not found in .agents/docs/changes or .agents/docs/archive")
        self.dir = candidates[0]
        self.spec = self.dir / "spec.md"
        self.reload()

    def reload(self) -> None:
        self.text = self.spec.read_text(encoding="utf-8")
        self.front, self.body = parse_front(self.text)
        self.status = self.front.get("status", "draft")
        self.acs = active_acs(self.body)

    def goal(self) -> str:
        lines = content(sections(self.body).get("Goal", ""))
        return lines[0] if lines else self.front.get("title", self.id)

    def adrs(self) -> list[str]:
        return as_list(self.front.get("adrs"))


def as_list(value) -> list[str]:
    return value if isinstance(value, list) else [value] if value else []


def doc_files(folder: str) -> list[Path]:
    path = DOCS / folder
    return sorted(path.glob("*.md")) if path.is_dir() else []


def open_slices() -> list[Slice]:
    changes = DOCS / "changes"
    folders = sorted(d for d in changes.iterdir() if d.is_dir()) if changes.is_dir() else []
    return [Slice(m.group(0)) for d in folders if (m := re.match(r"S-\d+", d.name))]


def load_adrs() -> dict[str, tuple[Path, dict]]:
    adrs = {}
    for path in doc_files("adr"):
        if m := re.match(r"ADR-\d+", path.name):
            adrs[m.group(0)] = (path, parse_front(path.read_text(encoding="utf-8"))[0])
    return adrs


# --- tests -------------------------------------------------------------------

def walk(base: Path):
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for name in filenames:
            path = Path(dirpath) / name
            if path.stat().st_size <= 1_000_000:
                yield path


def tagged_tests(sl: Slice, config: dict) -> dict[int, set[str]]:
    """Map each AC number to the test files that reference `S-XXX/AC-n`."""
    tag = re.compile(rf"\b{re.escape(sl.id)}/AC-(\d+)\b")
    found: dict[int, set[str]] = {}
    for base in config.get("tests", {}).get("paths", ["."]):
        for path in walk(ROOT / base):
            try:
                text = path.read_text(encoding="utf-8", errors="ignore")
            except OSError:
                continue
            for n in set(tag.findall(text)):
                found.setdefault(int(n), set()).add(path.relative_to(ROOT).as_posix())
    return found


def all_files(found: dict[int, set[str]]) -> list[str]:
    return sorted(set().union(*found.values())) if found else []


def support_files(config: dict) -> set[str]:
    """Files matching `tests.support`: helpers and fixtures frozen with the acceptance tests."""
    found = set()
    for pattern in config.get("tests", {}).get("support", []):
        for path in ROOT.glob(pattern.strip("/")):
            for file in [path] if path.is_file() else walk(path) if path.is_dir() else []:
                found.add(file.relative_to(ROOT).as_posix())
    return found


def is_support(relative: str, config: dict) -> bool:
    patterns = [p.strip("/") for p in config.get("tests", {}).get("support", [])]
    return any(fnmatch.fnmatchcase(relative, p) or fnmatch.fnmatchcase(relative, p + "/*") for p in patterns)


def digest(relative: str) -> str:
    return hashlib.sha256((ROOT / relative).read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def expand(args: list[str], slice_id: str, files: list[str]) -> list[str]:
    """Fill a test command: `{files}` and `{dirs}` become one argument per test file or folder,
    and `{id}` (`S-012`) and `{ident}` (`S012`, valid in test names) are replaced inside any argument."""
    dirs = sorted({"./" + parent if (parent := Path(f).parent.as_posix()) != "." else "." for f in files})
    expanded = []
    for arg in args:
        if arg in ("{files}", "{dirs}"):
            expanded += files if arg == "{files}" else dirs
        else:
            expanded.append(arg.replace("{id}", slice_id).replace("{ident}", slice_id.replace("-", "")))
    return expanded


def run_tests(config: dict, kind: str, slice_id: str, files: list[str] = ()) -> tuple[int | None, str]:
    command = config.get("tests", {}).get(kind)
    if not command:
        return None, f"tests.{kind} is not configured in .agents/config.toml"
    args = shlex.split(command, posix=os.name != "nt") if isinstance(command, str) else [str(a) for a in command]
    args = expand(args, slice_id, list(files))
    args[0] = shutil.which(args[0]) or args[0]
    print("$ " + " ".join(args), flush=True)
    try:
        return subprocess.run(args, cwd=ROOT).returncode, ""
    except OSError as error:
        return None, f"cannot run tests.{kind}: {error}"


# --- gates -------------------------------------------------------------------

def gate_ready(sl: Slice, config: dict, run: bool) -> list[str]:
    errors = []
    front = sl.front
    for key in ("id", "title", "capability", "change"):
        if not front.get(key):
            errors.append(f"front matter: '{key}' is missing")
    if front.get("id") and front["id"] != sl.id:
        errors.append(f"front matter: id is {front['id']}, expected {sl.id}")
    if front.get("change") and front["change"] not in CHANGES:
        errors.append(f"front matter: change must be one of {', '.join(CHANGES)}")
    if not isinstance(front.get("breaking"), (bool, list)):
        errors.append("front matter: breaking must be true, false or a list of release units")
    adrs = load_adrs()
    for ref in sl.adrs():
        if ref not in adrs:
            errors.append(f"{ref} does not exist in .agents/docs/adr")
        elif adrs[ref][1].get("status") == "superseded":
            errors.append(f"{ref} is superseded by {adrs[ref][1].get('superseded_by') or 'another ADR'}")
    found = sections(sl.body)
    for name in ("Goal", "In", "Out"):
        if not content(found.get(name, "")):
            errors.append(f"section '{name}' is empty")
    for label in ("Input", "Output", "Touches", "Contracts"):
        match = re.search(rf"\*\*{label}:\*\*[ \t]*(\S.*)?", found.get("Boundaries", ""))
        if not match or not match.group(1):
            errors.append(f"boundary '{label}' is empty (write 'none' if nothing applies)")
    if not 1 <= len(sl.acs) <= 6:
        errors.append(f"{len(sl.acs)} active acceptance criteria; expected 1-6 (split the slice if more)")
    for n, text in sl.acs:
        if not re.search(r"\bgiven\b.+\bwhen\b.+\bthen\b", text, re.I):
            errors.append(f"AC-{n} is not written as Given/When/Then")
    if content(found.get("Open questions", "")):
        errors.append("open questions remain")
    errors += [f"placeholder left in spec.md: {p}" for p in placeholders(sl.text)]
    return errors


def gate_red(sl: Slice, config: dict, run: bool) -> list[str]:
    errors = []
    found = tagged_tests(sl, config)
    active = {n for n, _ in sl.acs}
    for n in sorted(active - set(found)):
        errors.append(f"AC-{n} has no acceptance test tagged {sl.id}/AC-{n}")
    for n in sorted(set(found) - active):
        errors.append(f"tests reference {sl.id}/AC-{n}, which is not an active criterion")
    adrs = load_adrs()
    for ref in sl.adrs():
        status = adrs[ref][1].get("status") if ref in adrs else "missing"
        if status != "accepted":
            errors.append(f"{ref} is {status}; accept it with `sdd.py accept {ref}` once the user approves the spec")
    if run and not errors:
        code, error = run_tests(config, "slice", sl.id, all_files(found))
        expected = [int(c) for c in as_list(config.get("tests", {}).get("red_exit"))]
        if error:
            errors.append(error)
        elif code == 0:
            errors.append("acceptance tests pass; they must fail before implementation")
        elif expected and code not in expected:
            errors.append(f"acceptance tests exited with {code}, not {' or '.join(map(str, expected))} (tests.red_exit): "
                          "they must fail on missing behavior, not on a broken test or runner")
    return errors


def gate_green(sl: Slice, config: dict, run: bool) -> list[str]:
    errors = []
    frozen_path = sl.dir / ".frozen.json"
    if not frozen_path.exists():
        return ["no frozen acceptance tests (.frozen.json); advance the slice from ready first"]
    frozen = json.loads(frozen_path.read_text(encoding="utf-8"))
    tests = all_files(tagged_tests(sl, config))
    for path, expected in frozen.items():
        kind = "support file" if path not in tests and is_support(path, config) else "acceptance test"
        if not (ROOT / path).exists():
            errors.append(f"frozen {kind} removed: {path}")
        elif digest(path) != expected:
            errors.append(f"frozen {kind} modified: {path}")
    for path in sorted(set(tests) - set(frozen)):
        errors.append(f"acceptance test added after freeze: {path} (reopen the slice to change acceptance tests)")
    for path in sorted(support_files(config) - set(frozen)):
        errors.append(f"support file added after freeze: {path} (reopen the slice to change acceptance tests)")
    if run and not errors:
        for kind, files in (("slice", tests), ("full", [])):
            code, error = run_tests(config, kind, sl.id, files)
            if error or code != 0:
                errors.append(error or f"tests.{kind} failed")
                break
    return errors


def gate_done(sl: Slice, config: dict, run: bool) -> list[str]:
    errors = []
    close = sl.dir / "close.md"
    if not close.exists():
        errors.append("close.md is missing")
    else:
        text = close.read_text(encoding="utf-8")
        errors += [f"placeholder left in close.md: {p}" for p in placeholders(text)]
        errors += [f"close.md does not account for AC-{n}" for n, _ in sl.acs if not re.search(rf"\bAC-{n}\b", text)]
        if re.search(r"^\s*-\s*\[ \]", COMMENT_RE.sub("", text), re.M):
            errors.append("close.md has unchecked merge items")
    living = DOCS / "specs" / f"{sl.front.get('capability')}.md"
    if not living.exists():
        errors.append(f"living spec {living.relative_to(ROOT).as_posix()} is missing")
    else:
        text = living.read_text(encoding="utf-8")
        errors += [f"{sl.id}/AC-{n} is not merged into {living.name}" for n, _ in sl.acs if f"{sl.id}/AC-{n}" not in text]
    return errors


GATES = {"draft": gate_ready, "ready": gate_red, "red": gate_green, "green": gate_done}


def next_status(sl: Slice) -> str:
    if sl.status not in STATUSES:
        fail(f"{sl.id} has unknown status '{sl.status}'")
    if sl.status == "done":
        fail(f"{sl.id} is already done")
    return STATUSES[STATUSES.index(sl.status) + 1]


def report(sl: Slice, errors: list[str]) -> int:
    print(f"{sl.id}: {sl.status} -> {next_status(sl)}")
    for error in errors:
        print(f"  FAIL {error}")
    print("  gate passed" if not errors else f"  {len(errors)} problem(s)")
    return 1 if errors else 0


# --- index -------------------------------------------------------------------

def build_index() -> str:
    def link(path: Path) -> str:
        return path.relative_to(DOCS).as_posix()

    capabilities = []
    for path in doc_files("specs"):
        behaviors = re.findall(r"\*\*(S-\d+)/AC-\d+:\*\*", COMMENT_RE.sub("", path.read_text(encoding="utf-8")))
        last = max(behaviors, key=lambda s: int(s[2:]), default="")
        count = f"{len(behaviors)} behavior" + ("" if len(behaviors) == 1 else "s")
        capabilities.append(f"- [{path.stem}]({link(path)}) · {count}" + (f" · last {last}" if last else ""))
    adrs = load_adrs()
    decisions = {status: [
        f"- [{adr}]({link(path)}) {front.get('title', '')} · scope: {', '.join(as_list(front.get('scope'))) or 'none'}"
        for adr, (path, front) in adrs.items() if front.get("status") == status
    ] for status in ("accepted", "proposed")}
    slices = [f"- [{sl.id}]({link(sl.spec)}) {sl.status} · {sl.front.get('title', '')}" for sl in open_slices()]
    ideas = []
    for path in doc_files("ideas"):
        text = path.read_text(encoding="utf-8")
        front, _ = parse_front(text)
        if front.get("status", "open") == "open":
            pending = len(re.findall(r"^\|\s*C\d+\s*\|.*\|\s*candidate\s*\|\s*$", text, re.M))
            count = f"{pending} pending candidate" + ("" if pending == 1 else "s")
            ideas.append(f"- [{front.get('id', path.stem)}]({link(path)}) {front.get('title', '')} · {count}")
    runbooks = [f"- [{path.stem}]({link(path)})" for path in doc_files("runbooks")]
    context = [f"- [{name}]({name}.md)" for name in ("overview", "glossary") if (DOCS / f"{name}.md").exists()]

    text = INDEX_HEADER
    for title, rows in (
        ("Context", context), ("Capabilities", capabilities), ("Decisions (accepted)", decisions["accepted"]),
        ("Decisions (proposed)", decisions["proposed"]), ("Open slices", slices),
        ("Open ideas", ideas), ("Runbooks", runbooks),
    ):
        text += f"\n## {title}\n\n" + ("\n".join(rows) if rows else "- none") + "\n"
    return text


def write_index() -> None:
    DOCS.mkdir(parents=True, exist_ok=True)
    (DOCS / "index.md").write_text(build_index(), encoding="utf-8")


def generated_problems() -> list[str]:
    """Problems with the generated index and AGENTS.md block, or the single hint to initialize."""
    path = DOCS / "index.md"
    if not path.exists():
        return ["the harness is not initialized in this project: run the sdd-init skill (or `sdd.py init`)"]
    problems = []
    if path.read_text(encoding="utf-8") != build_index():
        problems.append(".agents/docs/index.md is stale: run `sdd.py index`")
    agents, text = agents_md()
    if with_agents_block(text) != text:
        problems.append(f"{agents.name} lacks the current sdd block: run `sdd.py init`")
    return problems


def with_agents_block(text: str) -> str:
    pattern = re.compile(re.escape(AGENTS_BEGIN) + r".*?" + re.escape(AGENTS_END), re.S)
    if pattern.search(text):
        return pattern.sub(lambda _: AGENTS_BLOCK, text, count=1)
    return (text.rstrip("\n") + "\n\n" if text.strip() else "") + AGENTS_BLOCK + "\n"


def agents_md() -> tuple[Path, str]:
    path = ROOT / "AGENTS.md"
    return path, path.read_text(encoding="utf-8") if path.exists() else ""


# --- commands ----------------------------------------------------------------

def cmd_init(args, config) -> int:
    path, text = agents_md()
    updated = with_agents_block(text)
    if updated != text:
        path.write_text(updated, encoding="utf-8")
        print(f"updated the sdd block in {path.name}")
    write_index()
    print("generated .agents/docs/index.md")
    return 0


